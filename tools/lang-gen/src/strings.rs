//! Parses `.strings` files (`"key" = "value";`, plural forms as `key#one`) and
//! emits the key constants and the English table.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use anyhow::{Context as _, bail, ensure};

/// tdesktop's plural form suffixes, in `i18n::PluralForm` order.
const FORMS: [&str; 6] = ["zero", "one", "two", "few", "many", "other"];

#[derive(Debug, Default)]
struct Entry {
    text: Option<String>,
    forms: [Option<String>; 6],
}

pub(crate) fn generate(sources: &[(&str, &str)], provenance: &str) -> anyhow::Result<String> {
    let mut entries: BTreeMap<String, Entry> = BTreeMap::new();
    for (name, source) in sources {
        for (key, value) in parse(source).with_context(|| format!("parsing {name}"))? {
            add(&mut entries, &key, value).with_context(|| format!("{name}: {key}"))?;
        }
    }
    emit(&entries, provenance)
}

fn add(entries: &mut BTreeMap<String, Entry>, key: &str, value: String) -> anyhow::Result<()> {
    let (base, form) = match key.split_once('#') {
        Some((base, form)) => (base, Some(form)),
        None => (key, None),
    };
    ensure!(
        base.bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_'),
        "keys are lowercase identifiers"
    );
    let entry = entries.entry(base.to_owned()).or_default();
    match form {
        None => {
            ensure!(entry.text.is_none(), "defined twice");
            entry.text = Some(value);
        }
        Some(form) => {
            let index = FORMS
                .iter()
                .position(|known| *known == form)
                .with_context(|| format!("unknown plural form {form}"))?;
            ensure!(entry.forms[index].is_none(), "defined twice");
            entry.forms[index] = Some(value);
        }
    }
    ensure!(
        entry.text.is_none() || entry.forms.iter().all(Option::is_none),
        "both plain and plural"
    );
    Ok(())
}

/// `"key" = "value";` pairs; `//` and `/* */` comments are skipped.
fn parse(source: &str) -> anyhow::Result<Vec<(String, String)>> {
    let chars: Vec<char> = source.chars().collect();
    let mut pairs = Vec::new();
    let mut i = 0;
    let skip_space = |i: &mut usize| -> anyhow::Result<()> {
        loop {
            match (chars.get(*i), chars.get(*i + 1)) {
                (Some(c), _) if c.is_whitespace() => *i += 1,
                (Some('/'), Some('/')) => {
                    while chars.get(*i).is_some_and(|c| *c != '\n') {
                        *i += 1;
                    }
                }
                (Some('/'), Some('*')) => {
                    *i += 2;
                    while !(chars.get(*i) == Some(&'*') && chars.get(*i + 1) == Some(&'/')) {
                        ensure!(*i < chars.len(), "unterminated comment");
                        *i += 1;
                    }
                    *i += 2;
                }
                _ => return Ok(()),
            }
        }
    };
    loop {
        skip_space(&mut i)?;
        if i >= chars.len() {
            return Ok(pairs);
        }
        let key = string(&chars, &mut i)?;
        skip_space(&mut i)?;
        ensure!(chars.get(i) == Some(&'='), "expected `=` after {key}");
        i += 1;
        skip_space(&mut i)?;
        let value = string(&chars, &mut i).with_context(|| format!("value of {key}"))?;
        skip_space(&mut i)?;
        ensure!(chars.get(i) == Some(&';'), "expected `;` after {key}");
        i += 1;
        pairs.push((key, value));
    }
}

fn string(chars: &[char], i: &mut usize) -> anyhow::Result<String> {
    ensure!(chars.get(*i) == Some(&'"'), "expected a string");
    *i += 1;
    let mut value = String::new();
    loop {
        match chars.get(*i) {
            None => bail!("unterminated string"),
            Some('"') => {
                *i += 1;
                return Ok(value);
            }
            Some('\\') => {
                match chars.get(*i + 1) {
                    Some('n') => value.push('\n'),
                    Some('"') => value.push('"'),
                    Some('\\') => value.push('\\'),
                    Some('t') => value.push('\t'),
                    other => bail!("unknown escape {other:?}"),
                }
                *i += 2;
            }
            Some(c) => {
                value.push(*c);
                *i += 1;
            }
        }
    }
}

fn emit(entries: &BTreeMap<String, Entry>, provenance: &str) -> anyhow::Result<String> {
    let mut out = String::new();
    writeln!(
        out,
        "// @generated by tools/lang-gen from {provenance} and crates/i18n/rgram.strings."
    )?;
    writeln!(
        out,
        "// Derived from Telegram Desktop (GPLv3); see NOTICE.md. Do not edit."
    )?;
    writeln!(out)?;
    writeln!(out, "use crate::Value;")?;
    writeln!(out)?;
    writeln!(
        out,
        "/// String keys, named as in tdesktop's `lang.strings` (`tr::lng_*`)."
    )?;
    writeln!(
        out,
        "#[allow(non_upper_case_globals, reason = \"tdesktop's key names\")]"
    )?;
    writeln!(out, "pub mod key {{")?;
    writeln!(out, "    use crate::Key;")?;
    for (index, name) in entries.keys().enumerate() {
        writeln!(out, "    pub const {name}: Key = Key({index});")?;
    }
    writeln!(out, "}}")?;
    writeln!(out)?;
    writeln!(
        out,
        "/// Key names in key order (sorted), for language packs."
    )?;
    writeln!(
        out,
        "pub(crate) static NAMES: [&str; {}] = [",
        entries.len()
    )?;
    for name in entries.keys() {
        writeln!(out, "    {name:?},")?;
    }
    writeln!(out, "];")?;
    writeln!(out)?;
    writeln!(out, "/// The English strings in key order.")?;
    writeln!(
        out,
        "pub(crate) static ENGLISH: [Value<&str>; {}] = [",
        entries.len()
    )?;
    for (name, entry) in entries {
        match &entry.text {
            Some(text) => writeln!(out, "    Value::Text({text:?}),")?,
            None => {
                let other = entry.forms[5]
                    .as_deref()
                    .with_context(|| format!("{name} has no #other form"))?;
                let forms: Vec<String> = entry
                    .forms
                    .iter()
                    .map(|form| format!("{:?}", form.as_deref().unwrap_or(other)))
                    .collect();
                writeln!(out, "    Value::Plural([{}]),", forms.join(", "))?;
            }
        }
    }
    writeln!(out, "];")?;
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_tdesktop_strings() {
        let source = "/*\nheader\n*/\n\"lng_a\" = \"One\\nTwo \\\"q\\\"\";\n// note\n\"lng_b#one\" = \"{count} chat\";\n\"lng_b#other\" = \"{count} chats\";\n";
        let code = generate(&[("test", source)], "fixture").unwrap();
        assert!(code.contains("pub const lng_a: Key = Key(0);"), "{code}");
        assert!(
            code.contains("Value::Text(\"One\\nTwo \\\"q\\\"\")"),
            "{code}"
        );
        assert!(
            code.contains("Value::Plural([\"{count} chats\", \"{count} chat\", \"{count} chats\""),
            "{code}"
        );
    }

    #[test]
    fn rejects_duplicates_and_mixed_entries() {
        assert!(generate(&[("t", "\"lng_a\" = \"x\";\"lng_a\" = \"y\";")], "f").is_err());
        assert!(generate(&[("t", "\"lng_a\" = \"x\";\"lng_a#one\" = \"y\";")], "f").is_err());
    }
}
