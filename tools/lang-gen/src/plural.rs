//! Translates the plural rules in tdesktop's `lang_tag.cpp` to Rust. The rules
//! are `ushort ChoosePluralX(int n, int i, int v, int w, int f, int t)`
//! functions made of `const auto` bindings, `if`/`else` and `return kShift*`,
//! which read the same in Rust; anything else stops the translation.

use std::fmt::Write as _;

use anyhow::{Context as _, anyhow, bail, ensure};

const SIGNATURE_START: &str = "ushort ChoosePlural";
const SIGNATURE_END: &str = "(int n, int i, int v, int w, int f, int t) {";

pub(crate) fn generate(source: &str, provenance: &str) -> anyhow::Result<String> {
    let lines: Vec<&str> = source.lines().collect();
    let mut functions = String::new();
    let mut names = Vec::new();
    let mut index = 0;
    while index < lines.len() {
        let line = lines[index];
        if let Some(rest) = line.strip_prefix(SIGNATURE_START)
            && let Some(name) = rest.strip_suffix(SIGNATURE_END)
        {
            let start = index + 1;
            let end = (start..lines.len())
                .find(|&i| lines[i] == "}")
                .ok_or_else(|| anyhow!("ChoosePlural{name} does not end"))?;
            writeln!(functions)?;
            writeln!(
                functions,
                "fn {}(n: i32, i: i32, v: i32, w: i32, f: i32, t: i32) -> PluralForm {{",
                function_name(name)
            )?;
            for (number, statement) in statements(&lines[start..end], start + 1) {
                let translated =
                    translate(&statement).with_context(|| format!("line {number}: {statement}"))?;
                writeln!(functions, "{translated}")?;
            }
            writeln!(functions, "}}")?;
            names.push(name.to_owned());
            index = end + 1;
        } else {
            index += 1;
        }
    }
    ensure!(!names.is_empty(), "no ChoosePlural functions found");

    let map = map_entries(&lines)?;
    for (_, rule) in &map {
        ensure!(
            names.contains(rule),
            "the map names unknown ChoosePlural{rule}"
        );
    }
    let default = lines
        .iter()
        .find_map(|line| {
            line.trim()
                .strip_prefix("const auto ChoosePluralDefault = &ChoosePlural")
                .and_then(|rest| rest.strip_suffix(';'))
        })
        .ok_or_else(|| anyhow!("ChoosePluralDefault not found"))?;

    let mut out = String::new();
    writeln!(out, "// @generated by tools/lang-gen from {provenance}.")?;
    writeln!(
        out,
        "// Derived from Telegram Desktop (GPLv3); see NOTICE.md. Do not edit."
    )?;
    writeln!(out, "//")?;
    writeln!(
        out,
        "// CLDR plural rules. n: the number, -1 if it is not an integer; i: its integer"
    )?;
    writeln!(
        out,
        "// digits; v, w: visible fraction digits with and without trailing zeros; f, t:"
    )?;
    writeln!(
        out,
        "// the fraction digits with and without trailing zeros."
    )?;
    writeln!(
        out,
        "#![allow(clippy::all, unused_parens, unused_variables, reason = \"translated from lang_tag.cpp\")]"
    )?;
    writeln!(out)?;
    writeln!(out, "use crate::PluralForm;")?;
    writeln!(out)?;
    writeln!(
        out,
        "pub(crate) type Rule = fn(i32, i32, i32, i32, i32, i32) -> PluralForm;"
    )?;
    writeln!(out)?;
    writeln!(
        out,
        "/// The rule of the English strings shipped in the app."
    )?;
    writeln!(
        out,
        "pub(crate) const DEFAULT: Rule = {};",
        function_name(default)
    )?;
    writeln!(out)?;
    writeln!(
        out,
        "/// The rule for a language pack, by tdesktop's lookup: the full tag, then"
    )?;
    writeln!(
        out,
        "/// the part before the first `-`, then a rule without plurals."
    )?;
    writeln!(out, "pub(crate) fn for_language(language: &str) -> Rule {{")?;
    writeln!(out, "    let key: String = language")?;
    writeln!(out, "        .chars()")?;
    writeln!(
        out,
        "        .map(|c| if c == '_' {{ '-' }} else {{ c.to_ascii_lowercase() }})"
    )?;
    writeln!(out, "        .collect();")?;
    writeln!(out, "    if let Some(rule) = by_key(&key) {{")?;
    writeln!(out, "        return rule;")?;
    writeln!(out, "    }}")?;
    writeln!(out, "    key.split_once('-')")?;
    writeln!(out, "        .and_then(|(parent, _)| by_key(parent))")?;
    writeln!(out, "        .unwrap_or({})", function_name("1"))?;
    writeln!(out, "}}")?;
    writeln!(out)?;
    writeln!(out, "fn by_key(key: &str) -> Option<Rule> {{")?;
    writeln!(out, "    Some(match key {{")?;
    for (language, rule) in &map {
        writeln!(out, "        {language:?} => {},", function_name(rule))?;
    }
    writeln!(out, "        _ => return None,")?;
    writeln!(out, "    }})")?;
    writeln!(out, "}}")?;
    out.push_str(&functions);
    Ok(out)
}

/// `{ "pt", ChoosePlural2hy },` entries of `GeneratePluralRulesMap`, skipping
/// commented-out ones.
fn map_entries(lines: &[&str]) -> anyhow::Result<Vec<(String, String)>> {
    let start = lines
        .iter()
        .position(|line| line.contains("GeneratePluralRulesMap() {"))
        .ok_or_else(|| anyhow!("GeneratePluralRulesMap not found"))?;
    let mut entries = Vec::new();
    for line in &lines[start + 1..] {
        let trimmed = line.trim();
        if trimmed == "};" {
            break;
        }
        let Some(entry) = trimmed
            .strip_prefix("{ \"")
            .and_then(|rest| rest.strip_suffix(" },"))
        else {
            continue;
        };
        let (language, rule) = entry
            .split_once("\", ChoosePlural")
            .ok_or_else(|| anyhow!("unexpected map entry {trimmed}"))?;
        if entries.iter().any(|(known, _)| known == language) {
            bail!("{language} is mapped twice");
        }
        entries.push((language.to_owned(), rule.to_owned()));
    }
    ensure!(!entries.is_empty(), "the plural map is empty");
    Ok(entries)
}

/// Body lines with multi-line `if` conditions joined, each with its first
/// line number.
fn statements(lines: &[&str], first_line: usize) -> Vec<(usize, String)> {
    let mut statements: Vec<(usize, String)> = Vec::new();
    let mut open = false;
    for (offset, line) in lines.iter().enumerate() {
        if open && let Some((_, statement)) = statements.last_mut() {
            statement.push(' ');
            statement.push_str(line.trim());
        } else {
            statements.push((first_line + offset, (*line).to_owned()));
        }
        let code = statements.last().map_or("", |(_, s)| s.trim());
        open =
            (code.starts_with("if (") || code.starts_with("} else if (")) && !code.ends_with(") {");
    }
    statements
}

fn translate(line: &str) -> anyhow::Result<String> {
    let indent = line.len() - line.trim_start().len();
    let indent = "    ".repeat(line[..indent].matches('\t').count());
    let code = line.trim();
    let translated = if code.is_empty() || code.starts_with("//") {
        code.to_owned()
    } else if let Some(binding) = code.strip_prefix("const auto ") {
        format!("let {binding}")
    } else if let Some(form) = code
        .strip_prefix("return kShift")
        .and_then(|rest| rest.strip_suffix(';'))
    {
        ensure!(
            matches!(form, "Zero" | "One" | "Two" | "Few" | "Many" | "Other"),
            "unknown plural form {form}"
        );
        format!("return PluralForm::{form};")
    } else if (code.starts_with("if (") || code.starts_with("} else if (")) && code.ends_with(") {")
        || code == "} else {"
        || code == "}"
    {
        code.to_owned()
    } else {
        bail!("unsupported C++");
    };
    Ok(format!("{indent}{translated}"))
}

/// `2fil` → `choose_plural_2fil`.
fn function_name(name: &str) -> String {
    format!("choose_plural_{}", name.to_ascii_lowercase())
}

#[cfg(test)]
mod tests {
    use super::*;

    const SOURCE: &str = "
ushort ChoosePlural1(int n, int i, int v, int w, int f, int t) {
\treturn kShiftOther;
}

ushort ChoosePlural2ast(int n, int i, int v, int w, int f, int t) {
\tif (i == 1 && v == 0) {
\t\treturn kShiftOne;
\t}
\treturn kShiftOther;
}

std::map<PluralsKey, ChoosePluralMethod> GeneratePluralRulesMap() {
\treturn {
\t\t//{ \"ja\", ChoosePlural1 },
\t\t{ \"en\", ChoosePlural2ast },
\t};
}
const auto ChoosePluralDefault = &ChoosePlural2ast;
";

    #[test]
    fn translates_rules_and_map() {
        let code = generate(SOURCE, "fixture").unwrap();
        assert!(code.contains("fn choose_plural_2ast(n: i32"), "{code}");
        assert!(
            code.contains("    if (i == 1 && v == 0) {\n        return PluralForm::One;"),
            "{code}"
        );
        assert!(code.contains("\"en\" => choose_plural_2ast,"), "{code}");
        assert!(!code.contains("\"ja\""), "{code}");
        assert!(
            code.contains("pub(crate) const DEFAULT: Rule = choose_plural_2ast;"),
            "{code}"
        );
    }

    #[test]
    fn stops_on_unknown_cpp() {
        let source = SOURCE.replace(
            "\treturn kShiftOther;\n}\n\nushort ChoosePlural2ast",
            "\tauto x = 1;\n}\n\nushort ChoosePlural2ast",
        );
        assert!(generate(&source, "fixture").is_err());
    }
}
