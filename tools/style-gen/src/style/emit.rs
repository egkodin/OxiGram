//! Emits evaluated `.style` modules as Rust: a struct per style struct type, a
//! `static` per struct variable, and a `const` per other variable. Colors stay
//! palette references so themes apply to them.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::PathBuf;

use anyhow::{Context as _, anyhow, bail, ensure};

use super::parser::{
    Color, FONT_BOLD, FONT_ITALIC, FONT_UNDERLINE, IconMask, Module, MonoIcon, Type, Value,
};

/// Types the style crate defines by hand; generated names must not clash.
const CORE_TYPES: &[&str] = &[
    "Align",
    "Color",
    "ColorId",
    "ColorRef",
    "Font",
    "FontFlags",
    "Icon",
    "IconMask",
    "Margins",
    "MonoIcon",
    "Palette",
    "Point",
    "Px",
    "Size",
];

const KEYWORDS: &[&str] = &[
    "as", "async", "await", "box", "break", "const", "continue", "crate", "do", "dyn", "else",
    "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl", "in", "let", "loop",
    "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref", "return", "self",
    "static", "struct", "super", "trait", "true", "try", "type", "typeof", "unsafe", "use",
    "virtual", "where", "while", "yield",
];

/// An icon image the generated code names, and where tdesktop keeps it.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub(crate) struct IconFile {
    pub(crate) name: String,
    pub(crate) path: PathBuf,
}

#[derive(Debug)]
pub(crate) struct Emitted {
    /// Rust module name and code, one per style module.
    pub(crate) modules: Vec<(String, String)>,
    pub(crate) icons: BTreeSet<IconFile>,
}

/// Emits every module but the palette. `provenance` names the source for the
/// file headers.
pub(crate) fn emit(modules: &[std::rc::Rc<Module>], provenance: &str) -> anyhow::Result<Emitted> {
    let mut owners: BTreeMap<String, String> = BTreeMap::new();
    let mut emitted = Emitted {
        modules: Vec::new(),
        icons: BTreeSet::new(),
    };
    let mut rust_names = BTreeSet::new();
    for module in modules {
        if module.name.ends_with(".palette") {
            continue;
        }
        let rust_name = module_name(&module.name)?;
        ensure!(
            rust_names.insert(rust_name.clone()),
            "two style modules map to {rust_name}"
        );
        for definition in &module.structs {
            ensure!(
                !CORE_TYPES.contains(&definition.name.as_str()),
                "struct {} clashes with a core style type",
                definition.name
            );
            owners.insert(definition.name.clone(), rust_name.clone());
        }
        let mut writer = ModuleWriter {
            module_name: &rust_name,
            owners: &owners,
            core: BTreeSet::new(),
            foreign: BTreeSet::new(),
            icons: &mut emitted.icons,
        };
        let body = writer
            .module(module)
            .with_context(|| format!("emitting {}", module.name))?;
        let mut code = String::new();
        writeln!(
            code,
            "// @generated by tools/style-gen from {} at {provenance}.",
            module.name
        )?;
        writeln!(
            code,
            "// Derived from Telegram Desktop (GPLv3); see NOTICE.md. Do not edit."
        )?;
        writeln!(code)?;
        if !writer.core.is_empty() {
            let core: Vec<_> = writer.core.iter().copied().collect();
            writeln!(code, "use crate::{{{}}};", core.join(", "))?;
        }
        for (owner, names) in group_foreign(&writer.foreign) {
            writeln!(code, "use crate::{owner}::{{{}}};", names.join(", "))?;
        }
        code.push_str(&body);
        emitted.modules.push((rust_name, code));
    }
    Ok(emitted)
}

fn group_foreign(foreign: &BTreeSet<(String, String)>) -> BTreeMap<&str, Vec<&str>> {
    let mut grouped: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for (owner, name) in foreign {
        grouped.entry(owner).or_default().push(name);
    }
    grouped
}

/// `ui/widgets/widgets.style` → `widgets`.
fn module_name(style_name: &str) -> anyhow::Result<String> {
    let stem = style_name
        .rsplit('/')
        .next()
        .and_then(|file| file.strip_suffix(".style"))
        .ok_or_else(|| anyhow!("unexpected style module name {style_name}"))?;
    Ok(snake_case(stem))
}

struct ModuleWriter<'a> {
    module_name: &'a str,
    owners: &'a BTreeMap<String, String>,
    core: BTreeSet<&'static str>,
    foreign: BTreeSet<(String, String)>,
    icons: &'a mut BTreeSet<IconFile>,
}

impl ModuleWriter<'_> {
    fn module(&mut self, module: &Module) -> anyhow::Result<String> {
        let mut out = String::new();
        for definition in &module.structs {
            writeln!(out)?;
            writeln!(out, "#[derive(Debug, Clone, Copy, PartialEq)]")?;
            writeln!(out, "pub struct {} {{", definition.name)?;
            let mut names = BTreeSet::new();
            for (field, ty) in &definition.fields {
                let rust_field = field_name(field);
                ensure!(
                    names.insert(rust_field.clone()),
                    "two fields of {} map to {rust_field}",
                    definition.name
                );
                writeln!(out, "    pub {rust_field}: {},", self.type_name(ty)?)?;
            }
            writeln!(out, "}}")?;
        }
        let mut names = BTreeSet::new();
        for variable in &module.variables {
            let name = constant_name(&variable.name);
            ensure!(names.insert(name.clone()), "two variables map to {name}");
            let ty = self.type_name(&variable.value.ty())?;
            let value = self
                .value(&variable.value, 0)
                .with_context(|| format!("in {}", variable.name))?;
            let item = if matches!(variable.value, Value::Struct { .. }) {
                "static"
            } else {
                "const"
            };
            writeln!(out)?;
            writeln!(out, "pub {item} {name}: {ty} = {value};")?;
        }
        Ok(out)
    }

    fn type_name(&mut self, ty: &Type) -> anyhow::Result<String> {
        let name = match ty {
            Type::Int => return Ok("i32".to_owned()),
            Type::Bool => return Ok("bool".to_owned()),
            Type::Double => return Ok("f64".to_owned()),
            Type::Str => return Ok("&'static str".to_owned()),
            Type::Pixels => "Px",
            Type::Color => "ColorRef",
            Type::Point => "Point",
            Type::Size => "Size",
            Type::Align => "Align",
            Type::Margins => "Margins",
            Type::Font => "Font",
            Type::Icon => "Icon",
            Type::Struct(name) => {
                self.use_struct(name)?;
                return Ok(name.clone());
            }
        };
        self.core.insert(name);
        Ok(name.to_owned())
    }

    fn use_struct(&mut self, name: &str) -> anyhow::Result<()> {
        let owner = self
            .owners
            .get(name)
            .ok_or_else(|| anyhow!("struct {name} is not defined by an emitted module"))?;
        if owner != self.module_name {
            self.foreign.insert((owner.clone(), name.to_owned()));
        }
        Ok(())
    }

    fn value(&mut self, value: &Value, depth: usize) -> anyhow::Result<String> {
        Ok(match value {
            Value::Int(v) => v.to_string(),
            Value::Bool(v) => v.to_string(),
            Value::Double(v) => format!("{v:?}"),
            Value::Pixels(v) => self.px(*v),
            Value::Str(v) => format!("{v:?}"),
            Value::Color(color) => self.color(color),
            Value::Point(x, y) => {
                self.core.insert("Point");
                format!("Point::new({x}, {y})")
            }
            Value::Size(w, h) => {
                self.core.insert("Size");
                format!("Size::new({w}, {h})")
            }
            Value::Align(align) => {
                self.core.insert("Align");
                format!("Align::{}", align_variant(align)?)
            }
            Value::Margins([l, t, r, b]) => {
                self.core.insert("Margins");
                format!("Margins::new({l}, {t}, {r}, {b})")
            }
            Value::Font(font) => {
                self.core.insert("Font");
                self.core.insert("FontFlags");
                let mut flags = Vec::new();
                for (bit, name) in [
                    (FONT_BOLD, "BOLD"),
                    (FONT_ITALIC, "ITALIC"),
                    (FONT_UNDERLINE, "UNDERLINE"),
                ] {
                    if font.flags & bit != 0 {
                        flags.push(format!("FontFlags::{name}"));
                    }
                }
                let flags = if flags.is_empty() {
                    "FontFlags::NONE".to_owned()
                } else {
                    flags.join(".union(") + &")".repeat(flags.len() - 1)
                };
                format!("Font::new({}, {flags}, {:?})", font.size, font.family)
            }
            Value::Icon(parts) => {
                self.core.insert("Icon");
                if parts.is_empty() {
                    "Icon::EMPTY".to_owned()
                } else {
                    let parts = parts
                        .iter()
                        .map(|part| self.mono_icon(part))
                        .collect::<anyhow::Result<Vec<_>>>()?;
                    format!("Icon::new(&[{}])", parts.join(", "))
                }
            }
            Value::Struct { ty, fields } => {
                self.use_struct(ty)?;
                let indent = "    ".repeat(depth + 1);
                let mut out = format!("{ty} {{\n");
                for field in fields {
                    let value = self.value(&field.value, depth + 1)?;
                    writeln!(out, "{indent}{}: {value},", field_name(&field.name))?;
                }
                out.push_str(&"    ".repeat(depth));
                out.push('}');
                out
            }
        })
    }

    fn px(&mut self, value: i32) -> String {
        self.core.insert("Px");
        format!("Px({value})")
    }

    fn color(&mut self, color: &Color) -> String {
        self.core.insert("ColorRef");
        match color {
            Color::Palette(name) => {
                self.core.insert("ColorId");
                format!("ColorRef::Palette(ColorId::{})", pascal_case(name))
            }
            Color::Rgba([r, g, b, a]) => {
                self.core.insert("Color");
                format!("ColorRef::Fixed(Color::rgba({r}, {g}, {b}, {a}))")
            }
        }
    }

    fn mono_icon(&mut self, icon: &MonoIcon) -> anyhow::Result<String> {
        self.core.insert("MonoIcon");
        self.core.insert("IconMask");
        let mask = match &icon.mask {
            IconMask::File {
                name,
                modifiers,
                path,
            } => {
                self.icons.insert(IconFile {
                    name: name.clone(),
                    path: path.clone(),
                });
                let modifiers: Vec<String> = modifiers.iter().map(|m| format!("{m:?}")).collect();
                format!(
                    "IconMask::File {{ name: {name:?}, modifiers: &[{}] }}",
                    modifiers.join(", ")
                )
            }
            IconMask::Rect { width, height } => {
                format!("IconMask::Rect(Size::new({width}, {height}))")
            }
        };
        if matches!(icon.mask, IconMask::Rect { .. }) {
            self.core.insert("Size");
        }
        let color = self.color(&icon.color);
        let [l, t, r, b] = icon.padding;
        self.core.insert("Margins");
        Ok(format!(
            "MonoIcon::new({mask}, {color}, Margins::new({l}, {t}, {r}, {b}))"
        ))
    }
}

fn align_variant(align: &str) -> anyhow::Result<&'static str> {
    Ok(match align {
        "topleft" => "TopLeft",
        "top" => "Top",
        "topright" => "TopRight",
        "right" => "Right",
        "bottomright" => "BottomRight",
        "bottom" => "Bottom",
        "bottomleft" => "BottomLeft",
        "left" => "Left",
        "center" => "Center",
        "justify" => "Justify",
        other => bail!("unknown align {other}"),
    })
}

/// `textFgOver` → `text_fg_over`; Rust keywords become raw identifiers.
fn field_name(name: &str) -> String {
    let snake = snake_case(name);
    if KEYWORDS.contains(&snake.as_str()) {
        format!("r#{snake}")
    } else {
        snake
    }
}

/// `introCoverTitle` → `INTRO_COVER_TITLE`.
fn constant_name(name: &str) -> String {
    snake_case(name).to_ascii_uppercase()
}

pub(crate) fn snake_case(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 4);
    let mut previous_lower = false;
    for c in name.chars() {
        if c.is_ascii_uppercase() {
            if previous_lower {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
            previous_lower = false;
        } else {
            out.push(c);
            previous_lower = c.is_ascii_lowercase() || c.is_ascii_digit();
        }
    }
    out
}

/// `windowBgOver` → `WindowBgOver`, the palette's `ColorId` variant.
pub(crate) fn pascal_case(name: &str) -> String {
    let mut chars = name.chars();
    chars.next().map_or_else(String::new, |first| {
        first.to_ascii_uppercase().to_string() + chars.as_str()
    })
}

#[cfg(test)]
mod tests {
    use super::super::parser::Loader;
    use super::*;

    #[test]
    fn emits_structs_and_values() {
        let dir = std::env::temp_dir().join(format!("style-gen-emit-{}", std::process::id()));
        std::fs::create_dir_all(dir.join("ui")).unwrap();
        std::fs::write(
            dir.join("ui/fixture.style"),
            "using \"ui/colors.palette\";
Ripple { color: color; duration: int; }
Button { width: pixels; font: font; align: align; ripple: Ripple; padding: margins; scale: double; }
fsize: 13px;
defaultRipple: Ripple { color: windowBgRipple; duration: 650; }
defaultButton: Button {
	width: -34px;
	font: font(fsize semibold);
	align: align(center);
	ripple: Ripple(defaultRipple) { color: transparent; }
	scale: 0.9;
}
wideButton: Button(defaultButton) { width: 300px; }
",
        )
        .unwrap();
        let mut loader = Loader::new(vec![dir.clone()], Vec::new(), vec!["windowBgRipple".into()]);
        let modules = loader.load("ui/fixture.style").unwrap().dependencies();
        let emitted = emit(&modules, "fixture").unwrap();
        std::fs::remove_dir_all(&dir).unwrap();
        assert_eq!(emitted.modules.len(), 1);
        insta::assert_snapshot!(emitted.modules[0].1);
    }

    #[test]
    fn names_follow_rust_conventions() {
        assert_eq!(snake_case("textFgOver"), "text_fg_over");
        assert_eq!(snake_case("introQrMaxSize"), "intro_qr_max_size");
        assert_eq!(snake_case("icon2x"), "icon2x");
        assert_eq!(
            constant_name("kLinkUnderlineNever"),
            "K_LINK_UNDERLINE_NEVER"
        );
        assert_eq!(field_name("type"), "r#type");
        assert_eq!(pascal_case("windowBg"), "WindowBg");
    }
}
