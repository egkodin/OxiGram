//! The emoji panel's sections from `lib_ui/emoji.txt`, read as
//! `codegen/emoji/data_read.cpp` reads it: the file's first part holds the
//! eight sections, the second replaces some of them with their emoji
//! lacking skin tones, which is what the panel lists. The last two make
//! one category, "Symbols & Flags".

use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context as _, bail};

pub const SOURCE: &str = "Telegram/lib_ui/emoji.txt";

/// The sections in the file.
const SECTION_COUNT: usize = 8;
/// The categories the panel shows after Recent (`Ui::Emoji::Section`);
/// the sections past the last one join it.
const CATEGORY_COUNT: usize = 7;

/// The file's parts, split by `--------` or `========` lines; each part's
/// sections, split by blank lines; each section's quoted emoji in order.
fn parse(text: &str) -> Vec<Vec<Vec<String>>> {
    let mut parts = vec![Vec::new()];
    let mut section: Vec<String> = Vec::new();
    let close = |parts: &mut Vec<Vec<Vec<String>>>, section: &mut Vec<String>| {
        if !section.is_empty() {
            parts
                .last_mut()
                .expect("parts start with one")
                .push(std::mem::take(section));
        }
    };
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with("--------") || trimmed.starts_with("========") {
            close(&mut parts, &mut section);
            parts.push(Vec::new());
        } else if trimmed.is_empty() {
            close(&mut parts, &mut section);
        } else {
            section.extend(
                trimmed
                    .split('"')
                    .skip(1)
                    .step_by(2)
                    .filter(|emoji| !emoji.is_empty())
                    .map(str::to_owned),
            );
        }
    }
    close(&mut parts, &mut section);
    parts
}

/// Each section as the panel lists it: the replacement starting with the
/// same emoji, else the section itself.
fn sections(parts: &[Vec<Vec<String>>]) -> anyhow::Result<Vec<Vec<String>>> {
    let (Some(main), Some(replacements)) = (parts.first(), parts.get(1)) else {
        bail!("emoji.txt has fewer parts than expected");
    };
    if main.len() != SECTION_COUNT {
        bail!("emoji.txt has {} sections, not {SECTION_COUNT}", main.len());
    }
    let mut categories: Vec<Vec<String>> = Vec::new();
    for (index, section) in main.iter().enumerate() {
        let listed = replacements
            .iter()
            .find(|replacement| replacement.first() == section.first())
            .unwrap_or(section);
        if index < CATEGORY_COUNT {
            categories.push(listed.clone());
        } else if let Some(last) = categories.last_mut() {
            last.extend(listed.iter().cloned());
        }
    }
    Ok(categories)
}

/// `crates/style/src/emoji.rs`.
pub fn generate(tdesktop: &Path, provenance: &str) -> anyhow::Result<String> {
    let path = tdesktop.join(SOURCE);
    let text =
        std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    let sections = sections(&parse(&text))?;
    let mut code = String::new();
    writeln!(
        code,
        "// @generated by tools/style-gen from {SOURCE} at {provenance}."
    )?;
    writeln!(
        code,
        "// Derived from Telegram Desktop (GPLv3); see NOTICE.md. Do not edit."
    )?;
    writeln!(code)?;
    writeln!(
        code,
        "/// The emoji panel's sections after Recent, in order: people, nature,"
    )?;
    writeln!(
        code,
        "/// food, activity, travel, objects, symbols and flags (`Ui::Emoji::Section`)."
    )?;
    writeln!(
        code,
        "pub const EMOJI_SECTIONS: [&[&str]; {CATEGORY_COUNT}] = ["
    )?;
    for section in sections {
        writeln!(code, "    &[")?;
        for emoji in section {
            writeln!(code, "        {emoji:?},")?;
        }
        writeln!(code, "    ],")?;
    }
    writeln!(code, "];")?;
    Ok(code)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn replacements_stand_in_for_sections_they_start_like() {
        let text = "\"a\",\"b\",\n\"c\",\n\n\"d\",\n========\n\"a\",\n\n--------\n\"x\",\n";
        let mut parts = parse(text);
        assert_eq!(parts[0], [vec!["a", "b", "c"], vec!["d"]]);
        assert_eq!(parts[1], [vec!["a"]]);
        assert_eq!(parts[2], [vec!["x"]]);
        // Pad to the panel's eight sections.
        for index in 0..6 {
            parts[0].push(vec![format!("s{index}")]);
        }
        let listed = sections(&parts).expect("eight sections");
        assert_eq!(listed[0], ["a"]);
        assert_eq!(listed[1], ["d"]);
        // The eighth joins the seventh.
        assert_eq!(listed.len(), 7);
        assert_eq!(listed[6], ["s4", "s5"]);
    }
}
