#!/bin/sh
# Regenerate the feature checklist from the parity registry.
set -eu

cd "$(dirname "$0")/.."
roadmap="$(mktemp)"
trap 'rm -f "$roadmap"' EXIT

awk -F'|' '
function trim(s) { gsub(/^[ \t]+|[ \t]+$/, "", s); return s }
function flush() {
    if (title == "") return
    printf "<details>\n<summary>%s · %d complete · %d in progress · %d planned</summary>\n\n", title, done, progress, planned
    printf "%s\n</details>\n", items
}
BEGIN {
    print "# Roadmap\n"
    print "[Read the parity registry](parity.md) for evidence and feature limits. It also lists items that do not apply to OxiGram.\n"
    print "This checklist is generated by `scripts/update-roadmap.sh`.\n"
}
/^## / {
    if (title != "") { flush(); print "" }
    title = substr($0, 4)
    sub(/ \(.*$/, "", title)
    items = ""; done = 0; progress = 0; planned = 0
    next
}
/^\| / {
    area = trim($2)
    if (area == "Area" || area ~ /^-+$/) next
    if (NF != 7 || trim($7) != "") {
        printf "Invalid table row at docs/parity.md:%d\n", NR > "/dev/stderr"; exit 1
    }
    feature = trim($3); milestone = trim($4); status = trim($5)
    if (status == "not applicable") next
    if (status == "done") { done++; box = "[x]"; label = "" }
    else if (status == "in progress") { progress++; box = "[ ]"; label = " · *In progress*" }
    else if (status == "todo") { planned++; box = "[ ]"; label = " · *Planned*" }
    else { printf "Invalid feature status at docs/parity.md:%d\n", NR > "/dev/stderr"; exit 1 }
    items = items "- " box " " feature " (" milestone ")" label "\n"
}
END { flush() }
' docs/parity.md > "$roadmap"

cat "$roadmap" > docs/roadmap.md
