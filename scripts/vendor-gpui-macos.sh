#!/usr/bin/env bash
# Re-creates vendor/gpui_macos from the Zed commit pinned in Cargo.toml and applies
# oxigram's patches from vendor/patches/ (ADR 0005). Run it after moving the gpui pin.
#
# Usage: scripts/vendor-gpui-macos.sh
#   Needs the pinned Zed checkout in ~/.cargo/git (any `cargo fetch` provides it) and
#   python3. The upstream crate inherits its manifest from Zed's workspace, so the
#   manifest is rebuilt from `cargo metadata` on that workspace, which reports
#   inherited dependencies fully resolved.
set -euo pipefail
shopt -s nullglob

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"
rev="$(grep -m1 -o 'zed", rev = "[0-9a-f]*"' Cargo.toml | cut -d'"' -f3)"
cargo_home="${CARGO_HOME:-$HOME/.cargo}"
zed_root="$(ls -d "$cargo_home"/git/checkouts/zed-*/"${rev:0:7}" 2>/dev/null | head -n1)"
[[ -n "$zed_root" ]] || { echo "no Zed checkout for $rev; run cargo fetch" >&2; exit 1; }
upstream="$zed_root/crates/gpui_macos"

target="vendor/gpui_macos"
rm -rf "$target"
mkdir -p "$target"
cp -R "$upstream/src" "$target/src"
cp -L "$upstream/LICENSE-APACHE" "$target/LICENSE-APACHE"

meta="$(mktemp)"
trap 'rm -f "$meta"' EXIT
cargo metadata --no-deps --offline --format-version 1 --manifest-path "$zed_root/Cargo.toml" > "$meta"
python3 - "$meta" "$rev" > "$target/Cargo.toml" <<'PY'
import json, sys
meta_path, rev = sys.argv[1], sys.argv[2]
zed = "https://github.com/zed-industries/zed"
with open(meta_path) as f:
    pkg = next(p for p in json.load(f)["packages"] if p["name"] == "gpui_macos")

def quoted(items):
    return "[" + ", ".join('"%s"' % i for i in items) + "]"

def spec(dep):
    # Path dependencies inside Zed's workspace become git dependencies on the same rev.
    fields = ['git = "%s"' % zed, 'rev = "%s"' % rev] if dep.get("path") else ['version = "%s"' % dep["req"]]
    if dep.get("rename"):
        fields.append('package = "%s"' % dep["name"])
    if not dep["uses_default_features"]:
        fields.append("default-features = false")
    if dep["features"]:
        fields.append("features = " + quoted(dep["features"]))
    if dep["optional"]:
        fields.append("optional = true")
    return "%s = { %s }" % (dep.get("rename") or dep["name"], ", ".join(fields))

out = [
    "# @generated by scripts/vendor-gpui-macos.sh from Zed %s; see ADR 0005." % rev[:9],
    "[package]",
    'name = "gpui_macos"',
    'version = "%s"' % pkg["version"],
    'edition = "%s"' % pkg["edition"],
    "publish = false",
    'license = "Apache-2.0"',
    "",
    "[lib]",
    'path = "src/gpui_macos.rs"',
    "doctest = false",
    "",
    "[features]",
]
out += ["%s = %s" % (name, quoted(items)) for name, items in sorted(pkg["features"].items())]
sections = {}
for dep in pkg["dependencies"]:
    if dep["kind"] != "dev":
        sections.setdefault(dep["target"], []).append(spec(dep))
for target, specs in sections.items():
    out += ["", "[dependencies]" if target is None else "[target.'%s'.dependencies]" % target]
    out += specs
print("\n".join(out))
PY

for patch in vendor/patches/gpui_macos-*.patch; do
  patch --quiet -p1 -d "$target" < "$patch"
done
echo "vendored gpui_macos from Zed ${rev:0:9}"
