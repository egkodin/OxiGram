//! Generates Rust bindings for TDLib's JSON API from `td_api.tl` (ADR 0003).
//!
//! The output has three modules, and every path in it is absolute, so generated
//! names (TDLib has types called `option`, `error`, …) never shadow std:
//!
//! - `types`: one struct per constructor;
//! - `enums`: one enum per abstract type with two or more constructors, tagged by
//!   `@type`. A type with a single constructor is represented by its struct;
//! - `functions`: one struct per function, implementing `crate::Function`.
//!
//! JSON conventions follow TDLib: `int64` is a string (`crate::int64` adapters),
//! `bytes` stays a base64 `String`, and fields documented as "may be null" or
//! "pass null" are `Option`. Object fields are boxed because the schema is
//! recursive.

use std::collections::{HashMap, HashSet};
use std::fmt::{self, Write as _};

use tdlib_rs_parser::parse_tl_file;
use tdlib_rs_parser::tl::{Category, Definition, Parameter, Type};

/// Why the schema could not be turned into Rust code.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum GenerateError {
    /// The schema does not start with TL's builtin block (`... = Vector t;`).
    #[error("schema does not start with the builtin type block")]
    MissingBuiltins,
    /// A definition after the builtin block failed to parse.
    #[error("definition #{index} does not parse: {reason}")]
    Parse { index: usize, reason: String },
    /// A field or result refers to a type the schema does not define.
    #[error("{context}: unknown type `{name}`")]
    UnknownType { context: String, name: String },
    /// Two definitions map to the same Rust item.
    #[error("two definitions map to `{0}`")]
    DuplicateName(String),
    /// A function returns a builtin type, which has no `@type` to decode.
    #[error("function `{0}` returns a builtin type")]
    BuiltinResult(String),
    /// Writing to the output buffer failed.
    #[error("formatting the output failed")]
    Format(#[from] fmt::Error),
}

/// The last line of TL's builtin block; real definitions follow it.
const BUILTINS_END: &str = "= Vector t;\n";

/// Generates the Rust source for `schema` (the contents of `td_api.tl`).
///
/// # Errors
///
/// Fails if any definition does not parse, refers to an unknown type, or
/// collides with another definition's Rust name.
pub fn generate(schema: &str) -> Result<String, GenerateError> {
    let (_, body) = schema
        .split_once(BUILTINS_END)
        .ok_or(GenerateError::MissingBuiltins)?;
    let definitions = parse_tl_file(body.to_owned())
        .enumerate()
        .map(|(index, parsed)| {
            parsed.map_err(|e| GenerateError::Parse {
                index,
                reason: format!("{e:?}"),
            })
        })
        .collect::<Result<Vec<_>, _>>()?;
    Schema::new(&definitions).emit()
}

/// How a TL type is represented in Rust.
enum Repr {
    Plain(&'static str),
    Int64,
    Vector(Box<Repr>),
    Object(String),
}

struct Schema<'a> {
    types: Vec<&'a Definition>,
    functions: Vec<&'a Definition>,
    /// Abstract type name to its constructors, in schema order.
    constructors: HashMap<&'a str, Vec<&'a Definition>>,
    /// Constructor name to its definition, for bare references like `user`.
    by_name: HashMap<&'a str, &'a Definition>,
}

impl<'a> Schema<'a> {
    fn new(definitions: &'a [Definition]) -> Self {
        let mut schema = Self {
            types: Vec::new(),
            functions: Vec::new(),
            constructors: HashMap::new(),
            by_name: HashMap::new(),
        };
        for definition in definitions {
            match definition.category {
                Category::Types => {
                    schema.types.push(definition);
                    schema
                        .constructors
                        .entry(&definition.ty.name)
                        .or_default()
                        .push(definition);
                    schema.by_name.insert(&definition.name, definition);
                }
                Category::Functions => schema.functions.push(definition),
            }
        }
        schema
    }

    fn emit(&self) -> Result<String, GenerateError> {
        let mut out = String::with_capacity(4 << 20);
        writeln!(
            out,
            "// @generated by td-api-gen from td_api.tl. Do not edit."
        )?;
        self.emit_types(&mut out)?;
        self.emit_enums(&mut out)?;
        self.emit_functions(&mut out)?;
        Ok(out)
    }

    fn emit_types(&self, out: &mut String) -> Result<(), GenerateError> {
        writeln!(out, "pub mod types {{")?;
        let mut seen = HashSet::new();
        for definition in &self.types {
            let name = pascal_case(&definition.name);
            if !seen.insert(name.clone()) {
                return Err(GenerateError::DuplicateName(format!("types::{name}")));
            }
            doc(out, &definition.description)?;
            writeln!(
                out,
                "#[derive(Debug, Clone, PartialEq, ::serde::Serialize, ::serde::Deserialize)]"
            )?;
            writeln!(out, "pub struct {name} {{")?;
            self.emit_fields(out, definition)?;
            writeln!(out, "}}")?;
        }
        writeln!(out, "}}")?;
        Ok(())
    }

    fn emit_enums(&self, out: &mut String) -> Result<(), GenerateError> {
        writeln!(out, "pub mod enums {{")?;
        let mut abstract_types: Vec<_> = self
            .constructors
            .iter()
            .filter(|(_, constructors)| constructors.len() > 1)
            .collect();
        abstract_types.sort_by_key(|(name, _)| **name);
        for (type_name, constructors) in abstract_types {
            let name = pascal_case(type_name);
            writeln!(
                out,
                "#[derive(Debug, Clone, PartialEq, ::serde::Serialize, ::serde::Deserialize)]"
            )?;
            writeln!(out, "#[serde(tag = \"@type\")]")?;
            writeln!(out, "pub enum {name} {{")?;
            let mut variants = HashSet::new();
            for constructor in constructors {
                let struct_name = pascal_case(&constructor.name);
                let variant = variant_name(&struct_name, &name);
                let variant = if variants.contains(&variant) {
                    struct_name.clone()
                } else {
                    variant
                };
                if !variants.insert(variant.clone()) {
                    return Err(GenerateError::DuplicateName(format!(
                        "enums::{name}::{variant}"
                    )));
                }
                doc(out, &constructor.description)?;
                writeln!(out, "#[serde(rename = \"{}\")]", constructor.name)?;
                writeln!(out, "{variant}(crate::types::{struct_name}),")?;
            }
            writeln!(out, "}}")?;
        }
        writeln!(out, "}}")?;
        Ok(())
    }

    fn emit_functions(&self, out: &mut String) -> Result<(), GenerateError> {
        writeln!(out, "pub mod functions {{")?;
        let mut seen = HashSet::new();
        for definition in &self.functions {
            let name = pascal_case(&definition.name);
            if !seen.insert(name.clone()) {
                return Err(GenerateError::DuplicateName(format!("functions::{name}")));
            }
            let response = match self.repr(&definition.ty, &definition.name)? {
                Repr::Object(path) => path,
                _ => return Err(GenerateError::BuiltinResult(definition.name.clone())),
            };
            doc(out, &definition.description)?;
            writeln!(
                out,
                "#[derive(Debug, Clone, PartialEq, ::serde::Serialize)]"
            )?;
            writeln!(
                out,
                "#[serde(tag = \"@type\", rename = \"{}\")]",
                definition.name
            )?;
            writeln!(out, "pub struct {name} {{")?;
            self.emit_fields(out, definition)?;
            writeln!(out, "}}")?;
            writeln!(out, "impl crate::Function for {name} {{")?;
            writeln!(out, "const NAME: &'static str = \"{}\";", definition.name)?;
            writeln!(out, "type Response = {response};")?;
            writeln!(out, "}}")?;
        }
        writeln!(out, "}}")?;
        Ok(())
    }

    fn emit_fields(&self, out: &mut String, definition: &Definition) -> Result<(), GenerateError> {
        for param in &definition.params {
            let context = format!("{}.{}", definition.name, param.name);
            let repr = self.repr(&param.ty, &context)?;
            let nullable = is_nullable(param);
            doc(out, &param.description)?;
            let (field, json_name) = field_name(&param.name);
            if let Some(json_name) = json_name {
                writeln!(out, "#[serde(rename = \"{json_name}\")]")?;
            }
            let ty = match &repr {
                Repr::Int64 => {
                    writeln!(out, "#[serde(with = \"crate::int64\")]")?;
                    "i64".to_owned()
                }
                Repr::Vector(inner) if matches!(**inner, Repr::Int64) => {
                    writeln!(out, "#[serde(with = \"crate::int64::vec\")]")?;
                    "::std::vec::Vec<i64>".to_owned()
                }
                Repr::Object(path) if nullable => {
                    writeln!(out, "#[serde(default)]")?;
                    format!("::std::option::Option<::std::boxed::Box<{path}>>")
                }
                Repr::Object(path) => format!("::std::boxed::Box<{path}>"),
                // "messages may be null": the elements are nullable, not the list.
                Repr::Vector(inner) if nullable => match &**inner {
                    Repr::Object(path) => {
                        format!("::std::vec::Vec<::std::option::Option<{path}>>")
                    }
                    _ => rust_type(&repr),
                },
                _ => rust_type(&repr),
            };
            writeln!(out, "pub {field}: {ty},")?;
        }
        Ok(())
    }

    fn repr(&self, ty: &Type, context: &str) -> Result<Repr, GenerateError> {
        let plain = match ty.name.as_str() {
            "Bool" => Some("bool"),
            "int32" => Some("i32"),
            "int53" => Some("i64"),
            "double" => Some("f64"),
            "string" | "bytes" => Some("::std::string::String"),
            _ => None,
        };
        if let Some(plain) = plain {
            return Ok(Repr::Plain(plain));
        }
        if ty.name == "int64" {
            return Ok(Repr::Int64);
        }
        if ty.name == "vector" {
            let inner = ty
                .generic_arg
                .as_deref()
                .ok_or_else(|| GenerateError::UnknownType {
                    context: context.to_owned(),
                    name: "vector without an element type".to_owned(),
                })?;
            return Ok(Repr::Vector(Box::new(self.repr(inner, context)?)));
        }
        let unknown = || GenerateError::UnknownType {
            context: context.to_owned(),
            name: ty.name.clone(),
        };
        if ty.bare {
            let definition = self.by_name.get(ty.name.as_str()).ok_or_else(unknown)?;
            return Ok(Repr::Object(format!(
                "crate::types::{}",
                pascal_case(&definition.name)
            )));
        }
        match self.constructors.get(ty.name.as_str()).map(Vec::as_slice) {
            Some([single]) => Ok(Repr::Object(format!(
                "crate::types::{}",
                pascal_case(&single.name)
            ))),
            Some([_, _, ..]) => Ok(Repr::Object(format!(
                "crate::enums::{}",
                pascal_case(&ty.name)
            ))),
            _ => Err(unknown()),
        }
    }
}

fn rust_type(repr: &Repr) -> String {
    match repr {
        Repr::Plain(name) => (*name).to_owned(),
        Repr::Int64 => "i64".to_owned(),
        Repr::Vector(inner) => format!("::std::vec::Vec<{}>", rust_type(inner)),
        Repr::Object(path) => path.clone(),
    }
}

fn is_nullable(param: &Parameter) -> bool {
    param.description.contains("may be null") || param.description.contains("pass null")
}

/// The Rust field name for a TL field, and the JSON name when the two differ
/// beyond a raw-identifier prefix.
fn field_name(name: &str) -> (String, Option<&str>) {
    const RESERVED: &[&str] = &[
        "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "do",
        "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl", "in",
        "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref",
        "return", "static", "struct", "trait", "true", "try", "type", "typeof", "unsafe",
        "unsized", "use", "virtual", "where", "while", "yield",
    ];
    // These cannot be raw identifiers.
    const UNRAWABLE: &[&str] = &["crate", "self", "super", "Self"];
    if UNRAWABLE.contains(&name) {
        (format!("{name}_"), Some(name))
    } else if RESERVED.contains(&name) {
        (format!("r#{name}"), None)
    } else {
        (name.to_owned(), None)
    }
}

/// `authorizationStateWaitCode` → `AuthorizationStateWaitCode`.
fn pascal_case(name: &str) -> String {
    let mut chars = name.chars();
    chars
        .next()
        .map(|first| first.to_ascii_uppercase().to_string() + chars.as_str())
        .unwrap_or_default()
}

/// The variant name of `struct_name` inside the enum `type_name`: the struct name
/// without the type prefix when what remains is a valid, readable identifier.
fn variant_name(struct_name: &str, type_name: &str) -> String {
    match struct_name.strip_prefix(type_name) {
        Some(rest) if rest != "Self" && rest.starts_with(|c: char| c.is_ascii_uppercase()) => {
            rest.to_owned()
        }
        _ => struct_name.to_owned(),
    }
}

fn doc(out: &mut String, text: &str) -> fmt::Result {
    for line in text.lines() {
        writeln!(out, "#[doc = {:?}]", escape_markdown(line.trim()))?;
    }
    Ok(())
}

/// TL descriptions are plain text; escaping keeps rustdoc from reading `[in]` as
/// a link or `<cite>` as an HTML tag.
fn escape_markdown(text: &str) -> String {
    let mut escaped = String::with_capacity(text.len());
    for c in text.chars() {
        if matches!(c, '\\' | '`' | '*' | '_' | '[' | ']' | '<' | '>') {
            escaped.push('\\');
        }
        escaped.push(c);
    }
    escaped
}

#[cfg(test)]
mod tests {
    use super::*;

    const SCHEMA: &str = "\
vector {t:Type} # [ t ] = Vector t;

//@description An error @code Error code @message Error message
error code:int32 message:string = Error;

//@description Ok
ok = Ok;

//@class OptionValue @description Represents the value of an option

//@description A string option @value The value
optionValueString value:string = OptionValue;

//@description An empty option
optionValueEmpty = OptionValue;

//@description A user @id Identifier @photo Photo; may be null @type The type @usernames Usernames
user id:int53 photo:OptionValue type:int64 usernames:vector<int64> = User;

//@description Messages @messages List of messages; messages may be null
messages messages:vector<user> = Messages;

---functions---

//@description Returns an option @name The name
getOption name:string = OptionValue;

//@description Closes
close = Ok;
";

    #[test]
    fn generates_types_enums_and_functions() {
        let code = generate(SCHEMA).unwrap();
        assert!(code.contains("pub struct Error {"));
        assert!(code.contains("pub enum OptionValue {"));
        assert!(code.contains(
            "#[serde(rename = \"optionValueString\")]\nString(crate::types::OptionValueString),"
        ));
        assert!(code.contains(
            "pub photo: ::std::option::Option<::std::boxed::Box<crate::enums::OptionValue>>,"
        ));
        assert!(code.contains("#[serde(with = \"crate::int64\")]\npub r#type: i64,"));
        assert!(code.contains(
            "#[serde(with = \"crate::int64::vec\")]\npub usernames: ::std::vec::Vec<i64>,"
        ));
        assert!(
            code.contains(
                "pub messages: ::std::vec::Vec<::std::option::Option<crate::types::User>>,"
            )
        );
        assert!(code.contains("type Response = crate::enums::OptionValue;"));
        assert!(code.contains("type Response = crate::types::Ok;"));
    }

    #[test]
    fn rejects_unknown_types() {
        let schema = "vector {t:Type} # [ t ] = Vector t;\nfoo bar:Missing = Foo;\n";
        let error = generate(schema).unwrap_err();
        assert!(matches!(error, GenerateError::UnknownType { name, .. } if name == "Missing"));
    }

    #[test]
    fn rejects_schemas_without_builtins() {
        assert!(matches!(
            generate("ok = Ok;"),
            Err(GenerateError::MissingBuiltins)
        ));
    }

    #[test]
    fn variant_names_drop_the_type_prefix_only_when_readable() {
        assert_eq!(
            variant_name("AuthorizationStateWaitCode", "AuthorizationState"),
            "WaitCode"
        );
        assert_eq!(variant_name("InputFileId", "InputFile"), "Id");
        assert_eq!(variant_name("ChatListMain", "Chat"), "ListMain");
        assert_eq!(variant_name("Reaction", "Reaction"), "Reaction");
        assert_eq!(variant_name("UserTypeSelf", "UserType"), "UserTypeSelf");
        assert_eq!(variant_name("Gift1", "Gift"), "Gift1");
    }

    #[test]
    fn doc_text_is_escaped_for_rustdoc() {
        assert_eq!(
            escape_markdown("[in ] X <cite> *_a_*"),
            r"\[in \] X \<cite\> \*\_a\_\*"
        );
    }

    #[test]
    fn reserved_field_names_are_escaped() {
        assert_eq!(field_name("type"), ("r#type".to_owned(), None));
        assert_eq!(field_name("self"), ("self_".to_owned(), Some("self")));
        assert_eq!(field_name("chat_id"), ("chat_id".to_owned(), None));
    }
}
